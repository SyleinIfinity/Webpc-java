CREATE OR REPLACE FUNCTION fn_tu_dong_het_han_otp_cu()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    UPDATE otp_log
    SET trang_thai = 'HetHan'
    WHERE email = NEW.email
      AND ma_log <> NEW.ma_log
      AND trang_thai = 'ConHan';
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_tu_dong_het_han_otp_cu
AFTER INSERT ON otp_log
FOR EACH ROW
EXECUTE FUNCTION fn_tu_dong_het_han_otp_cu();

CREATE OR REPLACE FUNCTION fn_cap_nhat_ton_kho_nhap_hang()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF TG_OP = 'INSERT' THEN
        UPDATE san_pham
        SET so_luong_ton = so_luong_ton + NEW.so_luong_nhap,
            gia_ban = NEW.gia_nhap * 1.2
        WHERE ma_san_pham = NEW.ma_san_pham;
        RETURN NEW;
    ELSIF TG_OP = 'DELETE' THEN
        UPDATE san_pham
        SET so_luong_ton = so_luong_ton - OLD.so_luong_nhap
        WHERE ma_san_pham = OLD.ma_san_pham;
        RETURN OLD;
    ELSE
        UPDATE san_pham
        SET so_luong_ton = so_luong_ton + (NEW.so_luong_nhap - OLD.so_luong_nhap),
            gia_ban = NEW.gia_nhap * 1.2
        WHERE ma_san_pham = NEW.ma_san_pham;
        RETURN NEW;
    END IF;
END;
$$;

