CREATE OR REPLACE PROCEDURE sp_dang_ky_khach_hang(
    IN p_ten_dang_nhap VARCHAR(50),
    IN p_mat_khau_hash VARCHAR(255),
    IN p_email VARCHAR(100),
    IN p_ho_ten VARCHAR(100),
    IN p_so_dien_thoai VARCHAR(15)
)
LANGUAGE plpgsql
AS $$
DECLARE
    v_ma_tai_khoan INTEGER;
    v_ma_khach_hang INTEGER;
BEGIN
    INSERT INTO tai_khoan (ten_dang_nhap, mat_khau_hash, email, trang_thai)
    VALUES (p_ten_dang_nhap, p_mat_khau_hash, p_email, 'Active')
    RETURNING ma_tai_khoan INTO v_ma_tai_khoan;

    INSERT INTO khach_hang (ho_ten, so_dien_thoai, email, ma_tai_khoan)
    VALUES (p_ho_ten, p_so_dien_thoai, p_email, v_ma_tai_khoan)
    RETURNING ma_khach_hang INTO v_ma_khach_hang;

    INSERT INTO gio_hang (ma_khach_hang) VALUES (v_ma_khach_hang);
END;
$$;

CREATE OR REPLACE PROCEDURE sp_them_vao_gio_hang(
    IN p_ma_khach_hang INTEGER,
    IN p_ma_san_pham INTEGER,
    IN p_so_luong INTEGER
)
LANGUAGE plpgsql
AS $$
DECLARE
    v_ma_gio_hang INTEGER;
BEGIN
    SELECT ma_gio_hang
    INTO v_ma_gio_hang
    FROM gio_hang
    WHERE ma_khach_hang = p_ma_khach_hang;

    IF v_ma_gio_hang IS NULL THEN
        RAISE EXCEPTION 'Khach hang chua co gio hang!';
    END IF;

    IF NOT EXISTS (
        SELECT 1
        FROM chi_tiet_gio_hang
        WHERE ma_gio_hang = v_ma_gio_hang
          AND ma_san_pham = p_ma_san_pham
    ) THEN
        INSERT INTO chi_tiet_gio_hang (ma_gio_hang, ma_san_pham, so_luong)
        VALUES (v_ma_gio_hang, p_ma_san_pham, p_so_luong);
    ELSE
        UPDATE chi_tiet_gio_hang
        SET so_luong = so_luong + p_so_luong
        WHERE ma_gio_hang = v_ma_gio_hang
          AND ma_san_pham = p_ma_san_pham;
    END IF;
END;
$$;

CREATE OR REPLACE PROCEDURE sp_tao_don_hang(
    IN p_ma_khach_hang INTEGER,
    IN p_ma_code_don_hang VARCHAR(50),
    IN p_dia_chi_giao VARCHAR(255),
    IN p_sdt_giao VARCHAR(15),
    IN p_nguoi_nhan VARCHAR(100),
    IN p_phuong_thuc_thanh_toan VARCHAR(20),
    IN p_ma_khuyen_mai_id INTEGER DEFAULT NULL
)
LANGUAGE plpgsql
AS $$
DECLARE
    v_ma_don_hang INTEGER;
    v_ma_gio_hang INTEGER;
BEGIN
    INSERT INTO don_hang (
        ma_code_don_hang,
        ma_khach_hang,
        ngay_dat,
        tong_tien,
        trang_thai,
        phuong_thuc_thanh_toan,
        dia_chi_giao_hang,
        so_dien_thoai_giao,
        nguoi_nhan
    )
    VALUES (
        p_ma_code_don_hang,
        p_ma_khach_hang,
        CURRENT_TIMESTAMP,
        0,
        'ChoXacNhan',
        p_phuong_thuc_thanh_toan,
        p_dia_chi_giao,
        p_sdt_giao,
        p_nguoi_nhan
    )
    RETURNING ma_don_hang INTO v_ma_don_hang;

    SELECT ma_gio_hang
    INTO v_ma_gio_hang
    FROM gio_hang
    WHERE ma_khach_hang = p_ma_khach_hang;

    INSERT INTO chi_tiet_don_hang (ma_don_hang, ma_san_pham, so_luong, don_gia_luc_mua, thanh_tien)
    SELECT
        v_ma_don_hang,
        ct.ma_san_pham,
        ct.so_luong,
        sp.gia_ban,
        (ct.so_luong * sp.gia_ban)
    FROM chi_tiet_gio_hang ct
    JOIN san_pham sp ON sp.ma_san_pham = ct.ma_san_pham
    WHERE ct.ma_gio_hang = v_ma_gio_hang;

    INSERT INTO giao_dich_thanh_toan (ma_don_hang, phuong_thuc, so_tien, trang_thai)
    VALUES (v_ma_don_hang, p_phuong_thuc_thanh_toan, 0, 'Pending');

    IF p_ma_khuyen_mai_id IS NOT NULL THEN
        UPDATE khuyen_mai_khach_hang
        SET da_su_dung = TRUE
        WHERE ma_khach_hang = p_ma_khach_hang
          AND ma_khuyen_mai = p_ma_khuyen_mai_id;
    END IF;

    DELETE FROM chi_tiet_gio_hang WHERE ma_gio_hang = v_ma_gio_hang;
END;
$$;

CREATE OR REPLACE FUNCTION fn_tinh_luong_nhan_vien(
    p_thang INTEGER,
    p_nam INTEGER
)
RETURNS TABLE (
    ma_nhan_vien INTEGER,
    ho_ten VARCHAR(100),
    ten_vai_tro VARCHAR(50),
    so_don_ban_duoc BIGINT,
    so_phieu_nhap BIGINT,
    luong_tam_tinh NUMERIC(18, 2)
)
LANGUAGE sql
AS $$
    SELECT
        nv.ma_nhan_vien,
        nv.ho_ten,
        vt.ten_vai_tro,
        (
            SELECT COUNT(*)
            FROM don_hang dh
            WHERE dh.ma_nhan_vien_duyet = nv.ma_nhan_vien
              AND EXTRACT(MONTH FROM dh.ngay_dat) = p_thang
              AND EXTRACT(YEAR FROM dh.ngay_dat) = p_nam
              AND dh.trang_thai = 'DaGiao'
        ) AS so_don_ban_duoc,
        (
            SELECT COUNT(*)
            FROM phieu_nhap pn
            WHERE pn.ma_nhan_vien_nhap = nv.ma_nhan_vien
              AND EXTRACT(MONTH FROM pn.ngay_nhap) = p_thang
              AND EXTRACT(YEAR FROM pn.ngay_nhap) = p_nam
        ) AS so_phieu_nhap,
        CASE
            WHEN vt.ten_vai_tro ILIKE '%Sales%' THEN
                5000000 + (
                    (
                        SELECT COUNT(*)
                        FROM don_hang dh
                        WHERE dh.ma_nhan_vien_duyet = nv.ma_nhan_vien
                          AND EXTRACT(MONTH FROM dh.ngay_dat) = p_thang
                          AND EXTRACT(YEAR FROM dh.ngay_dat) = p_nam
                          AND dh.trang_thai = 'DaGiao'
                    ) * 50000
                )
            WHEN vt.ten_vai_tro ILIKE '%Kho%' OR vt.ten_vai_tro ILIKE '%Admin%' THEN
                6000000 + (
                    (
                        SELECT COUNT(*)
                        FROM phieu_nhap pn
                        WHERE pn.ma_nhan_vien_nhap = nv.ma_nhan_vien
                          AND EXTRACT(MONTH FROM pn.ngay_nhap) = p_thang
                          AND EXTRACT(YEAR FROM pn.ngay_nhap) = p_nam
                    ) * 100000
                )
            ELSE 5000000
        END::NUMERIC(18, 2) AS luong_tam_tinh
    FROM nhan_vien nv
    JOIN vai_tro vt ON vt.ma_vai_tro = nv.ma_vai_tro;
$$;
