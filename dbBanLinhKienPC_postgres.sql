CREATE OR REPLACE FUNCTION fn_cap_nhat_ton_kho_ban_hang()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    v_so_luong_ton INTEGER;
BEGIN
    SELECT so_luong_ton
    INTO v_so_luong_ton
    FROM san_pham
    WHERE ma_san_pham = NEW.ma_san_pham
    FOR UPDATE;

    IF v_so_luong_ton IS NULL THEN
        RAISE EXCEPTION 'San pham % khong ton tai', NEW.ma_san_pham;
    END IF;

    IF v_so_luong_ton < NEW.so_luong THEN
        RAISE EXCEPTION 'Loi: San pham trong kho khong du de thuc hien don hang nay!';
    END IF;

    UPDATE san_pham
    SET so_luong_ton = so_luong_ton - NEW.so_luong
    WHERE ma_san_pham = NEW.ma_san_pham;

    RETURN NEW;
END;
$$;

