CREATE OR REPLACE FUNCTION fn_tinh_tong_tien_don_hang()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    v_ma_don_hang INTEGER;
BEGIN
    v_ma_don_hang := COALESCE(NEW.ma_don_hang, OLD.ma_don_hang);

    UPDATE don_hang
    SET tong_tien = COALESCE((
        SELECT SUM(thanh_tien)
        FROM chi_tiet_don_hang
        WHERE ma_don_hang = v_ma_don_hang
    ), 0) + COALESCE(phi_van_chuyen, 0)
    WHERE ma_don_hang = v_ma_don_hang;

    RETURN COALESCE(NEW, OLD);
END;
$$;

